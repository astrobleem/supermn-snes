def xlat_76_dispatch() -> str:
    """Compact exact dispatcher for otherwise-empty bank-$00 pages $76/$77."""

    targets = (
        (0x76B6, "entry_76b6"),
        (0x76BC, "entry_76bc"),
        (0x76C2, "entry_76c2"),
        (0x76D4, "entry_76d4"),
        (0x76EC, "entry_76ec"),
        (0x7704, "entry_7704"),
        (0x771C, "entry_771c"),
        (0x7734, "entry_7734"),
        (0x7748, "entry_7748"),
        (0x776A, "entry_776a"),
        (0x777A, "entry_777a"),
        (0x7782, "entry_7782"),
        (0x7786, "entry_7786"),
    )
    lines = [
        "; Compact continuation dispatcher for the one-shot $0076B6 fan-out.",
        "; $94:F900 admits only pages $76/$77; every unknown PC rejoins the",
        "; ordinary dense-table miss path without changing $40/$42.",
        "xlat_76_dispatch:",
        "    rep #$30",
        "    lda $42",
        "    bne xdd8_miss",
        "    lda $40",
    ]
    for pc, _entry in targets:
        lines.extend((f"    cmp #${pc:04X}", f"    beq xdd8_{pc:04x}"))
    lines.extend(("xdd8_miss:", "    jml.l xd_table"))
    for pc, entry in targets:
        lines.extend((f"xdd8_{pc:04x}:", f"    jmp {entry}"))
    lines.append("xlat_76_dispatch_end:")
    return "\n".join(lines)


def entry_76_chain() -> str:
    common = ("--coroutine", "--xflag", "--exitccr", "--restore-static-residue")

    first = transpile(
        0x0076B6,
        *common,
        "--real-return-calls=0076B6,0076BC",
    )
    first = direct_real_return(first, 0x0076B6, 0x024AA8, "entry_24aa8t")
    first = direct_real_return(first, 0x0076BC, 0x028F92, "entry_28f92t")
    first = sync_zero_move_ccr(first, 0x0076D2, "entry_76b6", z=0)
    first = guard_entry(first, "entry_76b6", 0x0076B6, bank_words=(0x36, 0x3E))
    pieces = [first + "\nentry_76b6_end:"]

    for pc, trap_pc in (
        (0x0076D4, 0x0076EA),
        (0x0076EC, 0x007702),
        (0x007704, 0x00771A),
        (0x00771C, 0x007732),
    ):
        body = transpile(pc, *common)
        body = sync_zero_move_ccr(body, trap_pc, f"entry_{pc:x}", z=0)
        body = guard_entry(body, f"entry_{pc:x}", pc, bank_words=(0x36, 0x3E))
        pieces.append(body + f"\nentry_{pc:x}_end:")

    tail = transpile(
        0x007734,
        *common,
        "--stopat=007786",
        "--real-return-calls=007742,007764,007774,00777C,007782",
    )
    for call_pc in (0x007742, 0x007764, 0x007774):
        tail = direct_real_return(tail, call_pc, 0x0008FA, "entry_8fat")
    tail = direct_real_return(tail, 0x00777C, 0x00091E, "entry_91et")
    tail = direct_real_return(
        tail, 0x007782, 0x0008B46, "entry_8b46t", same_bank=True
    )
    tail = guard_entry(
        tail, "entry_7734", 0x007734, bank_words=(0x36, 0x3A, 0x3E)
    )
    if not tail.endswith("entry_7786:\nbr7734_5:"):
        raise SystemExit("unexpected $007734 stop-at-$007786 seam")
    tail += (
        "\n    ; Continue byte-retained at the first post-$8B46 instruction;"
        "\n    ; this deliberately leaves the later trap-bearing control loop unchanged."
        "\n    lda #$7786"
        "\n    sta $40"
        "\n    lda #$0000"
        "\n    sta $42"
        "\n    jml.l inext"
        "\nentry_7734_end:"
    )
    pieces.append(tail)
    return "\n\n".join(pieces)


