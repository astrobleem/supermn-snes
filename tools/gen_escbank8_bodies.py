def entry_d7be() -> str:
    """Transpile the bounded round-transition initializer prefix.

    $00D7BE initializes the scrolling/strip state, selects two immutable ROM
    table rows, and then branches to the existing $00D9A8 allocator seam.
    It is reached with a genuine 68K return already on the task stack, so the
    table convention is exact.  The generated prefix has no nested calls and
    therefore does not depend on bank-$9D's synthetic-return sentinel even
    though the shared transpiler lowering is selected with ``--bank7``.
    """

    body = transpile(
        0x00D7BE,
        "--table",
        "--video",
        "--xflag",
        "--restore-indirect-residue",
        "--restore-static-residue",
    )
    body = guard_entry(
        body,
        "entry_d7be",
        0x00D7BE,
        exact_words=((0x34, 0x0000),),
        bank_words=(0x36, 0x3E),
    )
    # The prefix reads words at 4(A7) and 6(A7).  Direct bank-$40 indexing is
    # exact unless that final read crosses the 64 KiB work-RAM bank boundary.
    needle = (
        "    lda $3E\n"
        "    cmp #$00F0\n"
        "    bne hd7be_cold\n"
        "    bra hd7be_hot\n"
    )
    replacement = (
        "    lda $3E\n"
        "    cmp #$00F0\n"
        "    bne hd7be_cold\n"
        "    lda $3C\n"
        "    cmp #$FFF9\n"
        "    bcs hd7be_cold\n"
        "    clc\n"
        "    adc #$0006\n"
        "    sta $54\n"
        "    lda $3E\n"
        "    adc #$0000\n"
        "    sta $52\n"
        "    jsl.l rdw_ea_l\n"
        "    cmp #$0004\n"
        "    bne hd7be_cold\n"
        "    ; This exact N=4 path executes 84 original 68000 instructions.\n"
        "    ; The fetch loop charges the first; retain the other 83 here.\n"
        "    lda $AC\n"
        "    cmp #$0054\n"
        "    bcc hd7be_cold\n"
        "    bra hd7be_hot\n"
    )
    if body.count(needle) != 1:
        raise SystemExit("unexpected $00D7BE A7 guard seam")
    body = body.replace(needle, replacement, 1)
    # Keep every conservative restart distinguishable in execution-hook
    # evidence.  The AC restart is additionally bucketed so a live transition
    # can identify a safe continuation size without writing diagnostic state.
    guard_branches = (
        ("    bne hd7be_cold\n", "    bne hd7be_cold_a5_low\n"),
        ("    bne hd7be_cold\n", "    bne hd7be_cold_a5_bank\n"),
        ("    bne hd7be_cold\n", "    bne hd7be_cold_a7_bank\n"),
        ("    bcs hd7be_cold\n", "    bcs hd7be_cold_a7_cross\n"),
        ("    bne hd7be_cold\n", "    bne hd7be_cold_count\n"),
        ("    bcc hd7be_cold\n", "    bcc hd7be_cold_ac\n"),
    )
    for old, new in guard_branches:
        if old not in body:
            raise SystemExit(f"unexpected $00D7BE guard branch: {old.strip()}")
        body = body.replace(old, new, 1)
    cold = "hd7be_cold:\n"
    cold_diagnostics = """hd7be_cold_a5_low:
    bra hd7be_cold
hd7be_cold_a5_bank:
    bra hd7be_cold
hd7be_cold_a7_bank:
    bra hd7be_cold
hd7be_cold_a7_cross:
    bra hd7be_cold
hd7be_cold_count:
    bra hd7be_cold
hd7be_cold_ac:
    lda $AC
    cmp #$0010
    bcc hd7be_cold_ac_lt16
    cmp #$0020
    bcc hd7be_cold_ac_16_31
    cmp #$0030
    bcc hd7be_cold_ac_32_47
    cmp #$0040
    bcc hd7be_cold_ac_48_63
    bra hd7be_cold_ac_64_83
hd7be_cold_ac_lt16:
    bra hd7be_cold
hd7be_cold_ac_16_31:
    bra hd7be_cold
hd7be_cold_ac_32_47:
    bra hd7be_cold
hd7be_cold_ac_48_63:
    bra hd7be_cold
hd7be_cold_ac_64_83:
    bra hd7be_cold
"""
    if body.count(cold) != 1:
        raise SystemExit("unexpected $00D7BE cold restart label")
    body = body.replace(cold, cold_diagnostics + cold, 1)
    terminal = (
        "    lda #$D9A8\n"
        "    sta $40\n"
        "    lda #$0000\n"
        "    sta $42\n"
        "    jml.l inext"
    )
    charged_terminal = (
        "; The final SUBI.W reaches zero, then CMPI.W #0,D0 supplies the\n"
        "; architected exit CCR: X=0, N=0, Z=1, V=0, C=0.  The trailing\n"
        "; SUBA/MOVEA/BRA instructions do not alter it.\n"
        "    stz $A2\n"
        "    stz $70\n"
        "    lda #$0001\n"
        "    sta $60\n"
        "    stz $72\n"
        "    stz $6E\n"
        "    lda $AC\n"
        "    sec\n"
        "    sbc #$0053\n"
        "    sta $AC\n"
        + terminal
    )
    if body.count(terminal) != 1:
        raise SystemExit("unexpected $00D7BE -> $00D9A8 terminal seam")
    return body.replace(terminal, charged_terminal, 1) + "\nentry_d7be_end:"


