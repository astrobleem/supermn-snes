            *reads,
            "    beq h1c9ae_empty_hit",
            "    rep #$30",
            "    jmp h1c9ae_empty_cold",
            "h1c9ae_empty_hit:",
            "    rep #$30",
            "; MOVE.B #0,D4 changes only D4's low byte.",
            "    lda $10",
            "    and #$FF00",
            "    sta $10",
            "; Sixteen ADDA.W #$30 / DBRA iterations.",
            "    lda $20",
