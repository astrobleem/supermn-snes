def render_bg_offsets() -> bytes:
    """Return source-cell -> SNES top-left tilemap byte offsets.

    The producer scans the arcade planes in column-major blocks of 32 cells.
    Each 16x16 arcade cell expands to a 2x2 group in the split 64x32 SNES
    tilemap.  Keep this formula identical to video.pasm's one-time
    ``bg_offset_table_init`` so the SA-1 transition builder can replace its
    per-cell shift tree with one immutable ROM lookup.
    """

    output = bytearray()
    for column in range(16):
        for row in range(32):
            horizontal = column * 8 + (row & 1) * 4
            if horizontal & 0x40:
                horizontal = (horizontal & 0x3F) + 0x0800
            offset = (row & 0x1E) * 64 + horizontal
            output.extend(offset.to_bytes(2, "little"))
    if len(output) != 0x400:
        raise AssertionError("renderer BG offset table must be exactly 1024 bytes")
    return bytes(output)


def transpile(pc: int, *args: str, allow_rte_bail: bool = False) -> str:
    command = [
        sys.executable,
        str(ROOT / "tools/transpile.py"),
        f"{pc:06X}",
        "--bank7",  # banked helper/JML lowering; $00F8 returns resume bank $9D
        *args,
    ]
    result = subprocess.run(
        command,
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode:
        sys.stderr.write(result.stdout)
        sys.stderr.write(result.stderr)
        raise SystemExit(f"transpile failed for ${pc:06X}")
    if "UNIMPLEMENTED" in result.stdout:
        raise SystemExit(f"transpile emitted an incomplete body for ${pc:06X}")
    if "BAIL" in result.stderr:
        expected = "$0004FE rte" if allow_rte_bail else None
        if expected is None or result.stderr.count("BAIL edges") != 1 or expected not in result.stderr:
            sys.stderr.write(result.stderr)
            raise SystemExit(f"unexpected transpiler bail for ${pc:06X}")
    return result.stdout.rstrip()


def guard_entry(
    body: str,
    entry: str,
    pc: int,
    *,
    exact_words: tuple[tuple[int, int], ...] = (),
    bank_words: tuple[int, ...] = (),
) -> str:
    """Restart the original instruction before any direct-work-RAM mutation."""

    needle = f"{entry}:\n    rep #$30\n"
    tag = entry.removeprefix("entry_")
    lines = [needle.rstrip("\n")]
    for address, value in exact_words:
        lines.extend(
            [
                f"    lda ${address:02X}",
                f"    cmp #${value:04X}",
                f"    bne h{tag}_cold",
            ]
        )
    for address in bank_words:
        lines.extend(
            [
                f"    lda ${address:02X}",
                "    cmp #$00F0",
                f"    bne h{tag}_cold",
            ]
        )
    lines.extend(
        [
            f"    bra h{tag}_hot",
            f"h{tag}_cold:",
            f"    lda #${pc & 0xFFFF:04X}",
            "    sta $40",
            f"    lda #${(pc >> 16) & 0xFF:04X}",
            "    sta $42",
            "    jml.l inext",
            f"h{tag}_hot:",
        ]
    )
    replacement = "\n".join(lines) + "\n"
    if body.count(needle) != 1:
        raise SystemExit(f"unexpected entry prologue for {entry}")
    return body.replace(needle, replacement, 1)


def direct_real_return(
    body: str,
    call_pc: int,
    callee_pc: int,
    target: str,
    *,
    same_bank: bool = False,
) -> str:
    """Keep a genuine 68K return on the stack but enter a proven table body.

    ``--real-return-calls`` deliberately ends a span in ``inext``.  For callees
    that already have a table-convention body, the pushed architectural return
    is exactly that body's entry contract, so bypass only the interpreter fetch.
    The target PC remains in $40/$42 for guarded fallback paths.
    """

    ret = (call_pc + (4 if call_pc == 0x007782 else 6)) & 0xFFFFFF
    # The only BSR in this set is the four-byte $007782 instruction; all other
    # selected calls are six-byte absolute-long JSRs.
    needle = (
        f"    lda #${callee_pc & 0xFFFF:04X}\n"
        "    sta $40\n"
        f"    lda #${(callee_pc >> 16) & 0xFFFF:04X}\n"
        "    sta $42\n"
        "    jml.l inext\n"
        f"    ; xlat continuation transpiled from ${ret:06X}"
    )
    jump = f"    {'jmp' if same_bank else 'jml.l'} {target}"
    replacement = needle.replace("    jml.l inext", jump, 1)
    if body.count(needle) != 1:
        raise SystemExit(
            f"unexpected real-return bridge at ${call_pc:06X} -> ${callee_pc:06X}"
        )
    return body.replace(needle, replacement, 1)


def sync_zero_move_ccr(body: str, trap_pc: int, tag: str, *, z: int) -> str:
    """Materialize the final CLR/MOVE CCR before an interpreted TRAP."""

    needle = (
        f"    lda #${trap_pc & 0xFFFF:04X}\n"
        "    sta $40\n"
        f"    lda #${(trap_pc >> 16) & 0xFFFF:04X}\n"
        "    sta $42\n"
        "    jml.l inext"
    )
    sync = [
        "    ; The following interpreted TRAP stacks the 68K CCR.  Native",
        "    ; address/store plumbing clobbered host P, so publish the exact",
        "    ; final MOVE/CLR result while preserving X in $A2.",
        "    stz $70",
        "    stz $72",
        "    stz $6E",
    ]
    if z:
        sync.extend(("    lda #$0001", "    sta $60"))
    else:
        sync.append("    stz $60")
    replacement = "\n".join(sync) + "\n" + needle
    if body.count(needle) != 1:
        raise SystemExit(f"unexpected ${trap_pc:06X} TRAP tail in {tag}")
    return body.replace(needle, replacement, 1)


