"""Regenerate the packed round-start bodies in src/escbank6.pasm."""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/escbank6.pasm"
START = "; >>> ESCBANK6_BODIES — generated by tools/gen_escbank6_bodies.py <<<"
END = "; <<< ESCBANK6_BODIES <<<"
MID_START = "; >>> ESCBANK6_MID_BODIES — generated by tools/gen_escbank6_bodies.py <<<"
MID_END = "; <<< ESCBANK6_MID_BODIES <<<"
LATE_START = "; >>> ESCBANK6_LATE_COMBAT_BODIES — generated by tools/gen_escbank6_bodies.py <<<"
LATE_END = "; <<< ESCBANK6_LATE_COMBAT_BODIES <<<"
POST_LATE_START = "; >>> ESCBANK6_POST_LATE_BODIES — generated by tools/gen_escbank6_bodies.py <<<"
POST_LATE_END = "; <<< ESCBANK6_POST_LATE_BODIES <<<"

# (68K entry, xlat convention, extra transpiler arguments)
ROUTINES = [
    (0x00C8E0, "table", ["--escapes=00295a,0029b6"]),
    (0x00C9A6, "table", []),
    (0x00C722, "table", ["--escapes=00295a,0029b6"]),
    (0x00BBA4, "table", ["--workram=a1"]),
    # These two collision-response helpers contain dynamic renderer calls.
    # Charge every executed 68000 basic block so speeding them up cannot move
    # the virtual IRQ relative to the player task, and replace the private
    # bank-$95 bridge sentinel below A7 with the real $C672/$C712 residue.
    (0x00C60E, "table", [
        "--workram=a0",
        "--escapes=00295a,0029b6",
        "--accharge",
        "--restore-indirect-residue",
    ]),
    (0x00C6BC, "table", [
        "--workram=a0",
        "--escapes=00295a,0029b6",
        "--accharge",
        "--restore-indirect-residue",
    ]),
    (0x008D56, "table", []),
    (0x0074B8, "coroutine", []),
    (0x0074D4, "coroutine", []),
    (0x0074EC, "coroutine", []),
]

# $02A53A fits the audited $95:ADCC-$AEFF gap.  Keeping it out of the late
# generated stream leaves enough contiguous space for the cycle-accounted
# copied C-Chip routine before the fixed $95:F000 collision-pass island.
MID_ROUTINES = [
    (0x02A53A, "standard", ["--workram=a3,a4"]),
]

# These bodies live after the private-derived $95:B000-$B5AF DMA payload.
# $02A1B2 is a hand-written guarded adapter immediately before this generated
# block: state zero enters entry_2a1d8t, while every other state falls back to
# the interpreter at the original function entry.
LATE_ROUTINES = [
    (0x02A190, "coroutine", ["--escapes=02A1B2"]),
    (0x02A1D8, "table", [
        "--workram=a3,a4",
        "--escapes=02A53A,029128,029144,02A61E",
    ]),
    (0x029128, "standard", ["--workram=a4"]),
    (0x029144, "standard", [
        "--workram=a4",
        "--escapes=00111A",
        "--restore-indirect-residue",
    ]),
    (0x02A61E, "standard", ["--workram=a3,a4"]),
    # Sustained-gameplay eight-slot object updater. A1 is freshly based at
    # $F02BB4 on every pass; A2 remains ROM/RAM-aware because it walks object
    # scripts. Both static and indirect bridge returns retain genuine 68K
    # stack residue for full-window differential equivalence.
    (0x0175A0, "coroutine", [
        "--workram=a1",
        "--restore-indirect-residue",
        "--restore-static-residue",
        "--real-return-calls=0175E4,017610",
    ]),
    # Callback/yield loop and its $01770E real-return continuation.  Organic
    # gameplay uses D5 table indices through $10; the old $00..$0A bound sent
    # the dominant $10 path back through the interpreter.  Preserve the real
    # $01770E call return because the dynamic callback can cross a scheduler
    # yield, then keep the validated backward $176F6 edge inside this body.
    # Charge the virtual 68K instruction budget per basic block: this loop's
    # native speedup must not move the level-6 IRQ relative to coroutine work.
    (0x0176F6, "coroutine", [
        "--workram=a1",
        "--bail",
        "--accharge",
        "--restore-indirect-residue",
        "--restore-static-residue",
        "--real-return-calls=01770C",
        "--jt=01772A:0:16,0177A4:0:16",
    ]),
    # Object-state coroutine resumed after the $01C118 yield.  Both computed
    # branches are bounded by the 14-entry type tables; out-of-range indices
    # and the four cold unsupported arithmetic/bit edges re-enter the
    # interpreter at their original 68K PCs.  The generated entry also guards
    # A1: production legitimately passes ROM-backed table objects as well as
    # writable $F0xxxx objects.  MOVE-to-memory branch lowering currently
    # derives flags by rereading the destination, which is invalid after an
    # ignored ROM write, so those cold calls must remain interpreted.
    (0x01C11A, "coroutine", [
        "--bail",
        "--restore-static-residue",
        "--jt=01C130:0:26,01C2BC:0:26",
    ]),
]

POST_LATE_ROUTINES = [
    # The observed C-Chip boot response is copied verbatim to 68K RAM
    # $F01B20. Decode that private local input without embedding the raw blob
    # in source. This routine runs in the player death path, so charge every
    # executed 68000 basic block to keep IRQ/task boundaries exact.
    (0xF01B20, "table", [
        "--workram=a0",
        "--code-base=F01B20",
        "--code-file=data/cchip_boot_response.bin",
        "--accharge",
    ]),
]


def transpile(pc: int, convention: str, extra: list[str]) -> str:
    convention_args = [] if convention == "standard" else [f"--{convention}"]
    command = [
        sys.executable,
        str(ROOT / "tools/transpile.py"),
        f"{pc:06X}",
        "--bank6",
        *convention_args,
        "--exitccr",
        "--xflag",
        *extra,
    ]
    result = subprocess.run(
        command,
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode:
        sys.stderr.write(result.stdout)
        sys.stderr.write(result.stderr)
        raise SystemExit(f"transpile failed for ${pc:06X}")
    body = result.stdout.rstrip()
    if pc == 0x00C8E0:
        # The rejected compact-HLE experiment left a size-neutral redirect
        # seam at $95:8004.  Keep the label generated, not hand-edited inside
        # generated text, because build_interp_rom.py byte-audits this exact
        # original prologue before packing the bank.
        needle = "    lda $38\n"
        replacement = (
            "    lda $38\n"
            "entry_c8e0_generated_resume:\n"
            ".a16\n"
            ".i16\n"
        )
        if needle not in body:
            raise SystemExit("missing $C8E0 resume-seam instruction")
        body = body.replace(needle, replacement, 1)
    if pc == 0x02A190:
        # Expose a zero-byte oracle seam after the skipped BSR's genuine
        # $02A194 residue has been restored, but before the root's TST/branch
        # tail.  validate_2a190_native.py compares this point to MAME's common
        # $02A194 PC without having to execute either terminal trap.
        needle = (
            "    lda #$A194\n"
            "    xba\n"
            "    sta $400000,x\n"
            "    xba\n"
            "    lda $30\n"
        )
        replacement = (
            "    lda #$A194\n"
            "    xba\n"
            "    sta $400000,x\n"
            "    xba\n"
            "h2a190_after_bsr:\n"
            ".a16\n"
            ".i16\n"
            "    lda $0734\n"
            "    cmp #$2A19\n"
            "    bne h2a190_after_bsr_normal\n"
            "    lda #$A194\n"
            "    sta $40\n"
            "    lda #$0002\n"
            "    sta $42\n"
            "    jml.l inext\n"
            "h2a190_after_bsr_normal:\n"
            ".a16\n"
            ".i16\n"
            "    lda $30\n"
        )
        if body.count(needle) != 1:
            raise SystemExit("expected one $02A190 post-BSR residue seam")
        body = body.replace(needle, replacement, 1)
    if pc == 0x01C11A:
        # A1 is writable object state for the hot path, but an organic caller
        # also supplies ROM table records.  Fall back before changing any
        # emulated state when A1 is outside the only writable 68K RAM bank.
        needle = "entry_1c11a:\n    rep #$30\n"
        replacement = (
            "entry_1c11a:\n"
            "    rep #$30\n"
            "    lda $26\n"
            "    cmp #$00F0\n"
            "    beq h1c11a_workram\n"
            "    lda #$C11A\n"
            "    sta $40\n"
            "    lda #$0001\n"
            "    sta $42\n"
            "    jml.l inext\n"
            "h1c11a_workram:\n"
            ".a16\n"
            ".i16\n"
        )
        if body.count(needle) != 1:
            raise SystemExit("expected one $01C11A entry prologue")
        body = body.replace(needle, replacement, 1)
    if pc == 0x0175A0:
        # TST.W D1 feeds BGT at $0175C6.  The generic branch lowering only
        # materializes N/Z/V/C on the fall-through path; a taken BGT therefore
        # carried the preceding TST.W $A8(A1) Z bit through the final DBRA,
        # which itself does not affect CCR.  Materialize TST.W D1 before
        # either edge so a native continuation can safely finish the loop.
        needle = (
            "    lda $04\n"
            "    inc a\n"
            "    dec a\n"
            "    beq Lf175a0_5\n"
            "    bmi Lf175a0_5\n"
            "    jmp L175a0_175f8\n"
            "Lf175a0_5:\n"
            "    php\n"
            "    sep #$20\n"
            "    pla\n"
            "    rep #$30\n"
            "    and #$00FF\n"
            "    sta $50\n"
            "    and #$0002\n"
            "    sta $60\n"
            "    lda $50\n"
            "    and #$0080\n"
            "    sta $70\n"
            "    stz $72\n"
            "    stz $6E\n"
        )
        replacement = (
            "    lda $04\n"
            "    php\n"
            "    sep #$20\n"
            "    pla\n"
            "    rep #$30\n"
            "    and #$00FF\n"
            "    sta $50\n"
            "    and #$0002\n"
            "    sta $60\n"
            "    lda $50\n"
            "    and #$0080\n"
            "    sta $70\n"
            "    stz $72\n"
            "    stz $6E\n"
            "    lda $04\n"
            "    beq Lf175a0_5\n"
            "    bmi Lf175a0_5\n"
            "    jmp L175a0_175f8\n"
            "Lf175a0_5:\n"
        )
        if body.count(needle) != 1:
            raise SystemExit("expected one $0175A0 TST.W D1 branch")
        body = body.replace(needle, replacement, 1)
    if pc == 0xF01B20:
        # The copied queue routine has three CMPA.L outcomes that flow through
        # only flag-neutral MOVE/MOVEM/LEA/SUBQ-An/UNLK/RTS instructions.
        # Generic local-branch lowering keeps the native compare flags live
        # only for the immediate BNE/BEQ, so materialize the complete CMPA
        # N/Z/V/C at each terminal successor. CMPA, like CMP, preserves X.
        cmpa_ccr = (
            "    php\n"
            "    sep #$20\n"
            "    pla\n"
            "    rep #$30\n"
            "    and #$00FF\n"
            "    sta $50\n"
            "    and #$0002\n"
            "    sta $60\n"
            "    lda $50\n"
            "    and #$0080\n"
            "    sta $70\n"
            "    lda $50\n"
            "    and #$0040\n"
            "    sta $72\n"
            "    lda $50\n"
            "    and #$0001\n"
            "    eor #$0001\n"
            "    sta $6E\n"
        )
        for label in (
            "Lff01b20_6:",
            "Lff01b20_7:",
            "Lff01b20_8:",
        ):
            needle = label + "\n"
            if body.count(needle) != 1:
                raise SystemExit(
                    f"expected one $F01B20 terminal CMPA label {label}"
                )
            body = body.replace(needle, needle + cmpa_ccr, 1)
    if pc in (0x0176F6, 0x01770E):
        if pc == 0x0176F6:
            # MOVEM.L A1,$68(A1) likewise uses the pre-instruction A1 for
            # both the source value and destination EA.  A1 is guarded as
            # canonical work RAM for this native body, so lower the single
            # register store directly instead of immediately bailing out of
            # the hot coroutine loop.
            store_prefix = (
                "L176f6_176f6:\n"
                "    php\n"
                "    rep #$30\n"
                "    lda #$0006\n"
                "    jsr esc_ac_charge\n"
                "    plp\n"
            )
            store_needle = (
                store_prefix
                + "    ; BAIL to interp @ $0176F6: movem.l a1, $68(a1)   "
                "(movem operands 'a1, $68(a1)' (only -(An)/(An)+ "
                "supported))\n"
                "    lda #$76F6\n"
                "    sta $40\n"
                "    lda #$0001\n"
                "    sta $42\n"
                "    jml.l inext\n"
            )
            store_replacement = (
                store_prefix
                + "    lda $24\n"
                "    clc\n"
                "    adc #$0068\n"
                "    tax\n"
                "    lda $26\n"
                "    xba\n"
                "    sta $400000,x\n"
                "    xba\n"
                "    inx\n"
                "    inx\n"
                "    lda $24\n"
                "    xba\n"
                "    sta $400000,x\n"
                "    xba\n"
            )
            if body.count(store_needle) != 1:
                raise SystemExit("expected one $0176F6 MOVEM self-store")
            body = body.replace(store_needle, store_replacement, 1)

        # MOVEM.L $68(A1),A1 uses the pre-instruction A1 to form its EA and
        # does not touch A7.  Generic MOVEM restore lowering assumes (A7)+,
        # which is valid for epilogues but not this object self-restore.
        prefix = (
            "entry_1770e:\n"
            "br176f6_1:\n"
            if pc == 0x0176F6
            else ""
        )
        if "--accharge" in extra:
            prefix += (
                "    php\n"
                "    rep #$30\n"
                "    lda #$0007\n"
                "    jsr esc_ac_charge\n"
                "    plp\n"
            )
        legacy_needle = (
            prefix
            +
            "    ldx $3C\n"
            "    lda $400000,x\n"
            "    xba\n"
            "    sta $26\n"
            "    inx\n"
            "    inx\n"
            "    lda $400000,x\n"
            "    xba\n"
            "    sta $24\n"
            "    lda $3C\n"
            "    clc\n"
            "    adc #$0004\n"
            "    sta $3C\n"
        )
        bail_needle = (
            prefix
            + "    ; BAIL to interp @ $01770E: movem.l $68(a1), a1   "
            "(movem operands '$68(a1), a1' (only -(An)/(An)+ "
            "supported))\n"
            "    lda #$770E\n"
            "    sta $40\n"
            "    lda #$0001\n"
            "    sta $42\n"
            "    jml.l inext\n"
        )
        replacement = (
            prefix
            +
            "    lda $24\n"
            "    clc\n"
            "    adc #$0068\n"
            "    tax\n"
            "    lda $400000,x\n"
            "    xba\n"
            "    sta $26\n"
            "    inx\n"
            "    inx\n"
            "    lda $400000,x\n"
            "    xba\n"
            "    sta $24\n"
        )
        needle = (
            bail_needle
            if body.count(bail_needle) == 1
            else legacy_needle
        )
        if body.count(needle) != 1:
            raise SystemExit("expected one $01770E MOVEM self-restore")
        body = body.replace(needle, replacement, 1)

        if pc == 0x0176F6:
            # The state-4/state-5 callback paths end in one of two
            # architecturally visible flag producers before looping through
            # $176F6 and invoking another dynamic callback:
            #
            #   zero:    TST.W $E(A4)       -> Z=1, N/V/C=0
            #   nonzero: MOVE.W #1,(A1)     -> N/Z/V/C=0
            #
            # The generated branches consume the live host TST flags
            # correctly, but a direct native backedge otherwise leaves the
            # emulated CCR storage stale across the callback/IRQ boundary.
            # Route both outcomes through fixed helpers in the audited
            # $95:EFC0 seam.  Bound the replacements by stable 68000 labels;
            # generated Lf numbering changes whenever an earlier lowering
            # gains or loses a branch.
            callback_blocks = (
                ("L176f6_17814:\n", "L176f6_17838:\n"),
                ("L176f6_17838:\n", "L176f6_1785c:\n"),
            )
            for start_label, end_label in callback_blocks:
                start = body.find(start_label)
                end = body.find(end_label, start + len(start_label))
                if start < 0 or end < 0:
                    raise SystemExit(
                        "$0176F6 callback CCR block labels changed: "
                        f"{start_label.strip()}..{end_label.strip()}"
                    )
                block = body[start:end]
                root_jump = "    jmp L176f6_176f6\n"
                if block.count(root_jump) != 2:
                    raise SystemExit(
                        "$0176F6 callback block no longer has exactly two "
                        f"root backedges: {start_label.strip()}"
                    )
                block = block.replace(
                    root_jump,
                    "    jmp h176f6_tstw_zero_root\n",
                    1,
                )
                block = block.replace(
                    root_jump,
                    "    jmp h176f6_move_one_root\n",
                    1,
                )
                body = body[:start] + block + body[end:]
            if (
                body.count("    jmp h176f6_tstw_zero_root\n") != 2
                or body.count("    jmp h176f6_move_one_root\n") != 2
            ):
                raise SystemExit(
                    "$0176F6 callback CCR helper routing is incomplete"
                )
    if convention == "table":
        old = f"entry_{pc:x}:"
        new = f"entry_{pc:x}t:"
        if body.count(old) != 1:
            raise SystemExit(f"expected one {old} label")
        body = body.replace(old, new, 1)
    if "--accharge" in extra:
        calls = body.count("    jsr esc_ac_charge\n")
        if not calls:
            raise SystemExit(f"missing AC-charge calls in ${pc:06X}")
        # The transpiler's canonical helper is local to escape bank $94.
        # Bank $95 carries the same leaf under a bank-local name so every
        # generated JSR retains its 16-bit return and stack behavior.
        body = body.replace("    jsr esc_ac_charge\n", "    jsr esc6_ac_charge\n")
    args = " ".join(command[3:])
    return f"; command: tools/transpile.py {pc:06X} {args}\n{body}"


def main() -> int:
    source = SOURCE.read_text()
    groups = (
        (START, END, ROUTINES),
        (MID_START, MID_END, MID_ROUTINES),
        (LATE_START, LATE_END, LATE_ROUTINES),
        (POST_LATE_START, POST_LATE_END, POST_LATE_ROUTINES),
    )
    total = 0
    for start, end, routines in groups:
        pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
        if not pattern.search(source):
            raise SystemExit(f"escbank6 body markers missing: {start}")
        bodies = "\n\n".join(transpile(*spec) for spec in routines)
        replacement = f"{start}\n{bodies}\n{end}"
        source = pattern.sub(lambda _: replacement, source, count=1)
        total += len(routines)
    SOURCE.write_text(source)
    print(f"gen_escbank6_bodies: wrote {total} bodies")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
