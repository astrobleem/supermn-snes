if not SOURCE.exists():
    raise SystemExit(0)
resolved: list[tuple[str, int]] = []
for symbols, mapped_bank, needed in IMPORTS:
    if not symbols.exists():
        sys.exit(f"gen_escbank7_syms: {symbols} missing")
    available: dict[str, int] = {}
    for raw in symbols.read_text(encoding="utf-8-sig").splitlines():
        match = re.match(r"\s*00:([0-9A-Fa-f]{4})\s+(\S+)", raw)
        if match:
            available[match.group(2)] = int(match.group(1), 16)
    missing = [name for name in needed if name not in available]
    if missing:
        sys.exit(f"gen_escbank7_syms: missing {symbols} symbols: {missing}")
    resolved.extend(
        (name, (mapped_bank << 16) | available[name]) for name in needed
    )

lines = [
    "; >>> ESCBANK7_SYMS — auto-generated by tools/gen_escbank7_syms.py (do not edit) <<<"
]
lines.extend(f"{name}=${address:06X}" for name, address in resolved)
lines.append("; <<< ESCBANK7_SYMS <<<")
block = "\n".join(lines)

source = SOURCE.read_text(encoding="utf-8")
pattern = re.compile(
    r"; >>> ESCBANK7_SYMS.*?; <<< ESCBANK7_SYMS <<<", re.DOTALL
)
if not pattern.search(source):
    sys.exit("gen_escbank7_syms: marked symbol block missing")
SOURCE.write_text(pattern.sub(block, source), encoding="utf-8")
print(f"gen_escbank7_syms: wrote {len(resolved)} symbols")
